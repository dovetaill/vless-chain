// Real panel/Agent logs; only failure and privileged time actions are simulated.
const assert = require('node:assert/strict');
const fs = require('node:fs');
const path = require('node:path');
const { chromium } = require(process.env.CHAIN_TEST_BROWSER);
const [base, tokenFile, root, agentDir, lineId] = process.argv.slice(2);
(async () => {
  const server = await chromium.launchServer({headless:true, executablePath:process.env.CHAIN_TEST_CHROMIUM});
  fs.writeFileSync(path.join(root,'diagnostics-browser.json'),JSON.stringify({pid:process.pid,browser:server.process().pid,endpoint:server.wsEndpoint()}));
  const browser = await chromium.connect(server.wsEndpoint());
  try {
    const page = await browser.newPage({viewport:{width:1440,height:1000},locale:'zh-CN'});
    page.setDefaultTimeout(20000);
    const errors=[]; page.on('pageerror',e=>errors.push(e.message));
    let reads=0; page.on('request',r=>{if(r.url().endsWith('/logs'))reads++;});
    const button=name=>page.getByRole('button',{name,exact:true});
    const dialog=()=>page.getByRole('dialog');
    const close=async()=>{await dialog().getByRole('button',{name:'关闭',exact:true}).last().click();await dialog().waitFor({state:'hidden'});};
    await page.goto(base+'/admin');
    await page.getByLabel('管理员密钥',{exact:true}).fill(fs.readFileSync(tokenFile,'utf8').trim());
    await button('登录').click();
    await page.locator('aside nav').getByRole('button',{name:/^代理/}).click();
    await button('浏览器诊断代理 更多操作').click();
    await page.getByRole('menuitem',{name:'日志与诊断',exact:true}).click();
    const originalURL=page.url();
    await dialog().getByText(/fixture-live/).waitFor();
    assert.equal(page.url(),originalURL);
    await button('暂停跟随').click();
    const paused=reads;
    fs.appendFileSync(path.join(agentDir,'xray.log'),`\n${Math.floor(Date.now()/1000)} line-${lineId}-in fixture-new\n`);
    await page.waitForTimeout(3400);
    assert.equal(reads,paused,'Paused view must not poll');
    assert.match(await dialog().locator('pre').last().innerText(),/fixture-live/,'Pause keeps current logs');
    await button('继续跟随').click();
    await dialog().getByText(/fixture-new/).waitFor();
    await page.getByLabel('包含近期归档').check();
    await dialog().getByText(/fixture-archive/).waitFor();
    assert.doesNotMatch(await dialog().locator('pre').last().innerText(),/fixture-password/);
    const download=page.waitForEvent('download');await button('下载脱敏日志').click();
    const file=await download;const dest=path.join(root,'logs.txt');await file.saveAs(dest);
    assert.match(fs.readFileSync(dest,'utf8'),/fixture-archive/);
    assert.doesNotMatch(fs.readFileSync(dest,'utf8'),/fixture-password/);
    await page.route('**/api/diagnostics/*/path',r=>r.fulfill({json:{stage:'外部出口',result:{ok:false,detail:'certificate is not yet valid'},note:'隔离检查'}}));
    await page.getByText('分段连接检查',{exact:true}).click();
    await button('开启 10 分钟详细诊断窗口').click();await button('执行详细检查').click();
    await dialog().getByText(/入口尚未验证/).waitFor();
    let tasks=0;
    await page.route('**/api/federation/task',r=>{tasks++;return r.fulfill({json:r.request().postDataJSON().action==='status'?{state:'succeeded',detail:'模拟校时完成'}:{}});});
    page.once('dialog',d=>d.dismiss());await button('启用本 VPS 自动校时').click();assert.equal(tasks,0);
    page.once('dialog',d=>d.accept());await button('启用本 VPS 自动校时').click();
    await page.getByText('模拟校时完成',{exact:true}).waitFor();assert.equal(tasks,2);
    await page.screenshot({path:path.join(root,'diagnostics-desktop.png')});
    await page.setViewportSize({width:390,height:844});
    await page.waitForFunction(()=>{const r=document.querySelector('[role=dialog]').getBoundingClientRect();return r.top>=0 && r.bottom<=innerHeight;});
    await dialog().evaluate(el=>el.scrollTop=0);
    await page.screenshot({path:path.join(root,'diagnostics-mobile.png'),animations:'disabled'});
    assert.ok(await dialog().evaluate(el=>el.getBoundingClientRect().right<=window.innerWidth),'Dialog fits mobile viewport');
    await close();const stopped=reads;await page.waitForTimeout(3400);assert.equal(reads,stopped,'Closing stops polling');
    await page.setViewportSize({width:1440,height:1000});
    await button('浏览器诊断代理 更多操作').click();await page.getByRole('menuitem',{name:'日志与诊断',exact:true}).click();
    await page.route('**/api/diagnostics/*/logs',r=>r.fulfill({status:400,json:{error:'Agent 离线，无法读取新日志'}}));
    await button('刷新日志').click();await page.getByRole('alert').filter({hasText:'Agent 离线'}).waitFor();
    await close();assert.deepEqual(errors,[]);
    console.log('PASS real browser: Agent logs, follow/pause/close, archives, redacted download, isolated failure guidance, simulated time confirmation, desktop/mobile');
  } finally {await browser.close();await server.close();}
})().catch(e=>{console.error(e);process.exitCode=1;});
