// Real UI and WebAuthn acceptance tests against smoke.py's isolated controller.
const fs = require('node:fs');
const path = require('node:path');
const assert = require('node:assert/strict');
const { chromium } = require(process.env.CHAIN_TEST_BROWSER);
const [address, tokenFile, artifacts, forwardingPort] = process.argv.slice(2);
const base = address.replace('127.0.0.1', 'localhost');

(async () => {
  const screenshots = path.join(artifacts, 'screenshots');
  fs.mkdirSync(screenshots, { recursive: true });
  const record = { cwd: process.cwd(), pid: process.pid, artifacts, browserPid: null };
  const recordFile = path.join(artifacts, 'browser-ownership.json');
  fs.writeFileSync(recordFile, JSON.stringify(record));
  const server = await chromium.launchServer({ headless: true, executablePath: process.env.CHAIN_TEST_CHROMIUM });
  record.browserPid = server.process().pid;
  fs.writeFileSync(recordFile, JSON.stringify(record));
  let browser;
  try {
    browser = await chromium.connect(server.wsEndpoint());
    const context = await browser.newContext({ viewport: { width: 1440, height: 1000 }, locale: 'zh-CN' });
    const page = await context.newPage();
    const errors = [];
    page.on('pageerror', e => errors.push(e.message));
    const button = name => page.getByRole('button', { name, exact: true });
    const heading = name => page.getByRole('heading', { name, exact: true });
    const close = async () => { await page.getByRole('dialog').getByRole('button', { name: '关闭', exact: true }).last().click(); await page.getByRole('dialog').waitFor({ state: 'hidden' }); };
    const shot = async name => {
      await page.mouse.move(1430, 0);
      await page.screenshot({ path: path.join(screenshots, name + '.png'), fullPage: await page.getByRole('dialog').count() === 0, animations: 'disabled' });
    };
    const nav = async name => { await page.locator('aside nav').getByRole('button', { name: new RegExp('^' + name) }).click(); await page.getByRole('heading', { name, exact: true, level: 1 }).waitFor(); };
    await page.goto(base + '/admin');
    await heading('登录控制台').waitFor();
    await shot('login');
    await page.getByLabel('管理员密钥', { exact: true }).fill('incorrect');
    await button('登录').click();
    await page.getByRole('alert').waitFor();
    await page.getByLabel('管理员密钥', { exact: true }).fill(fs.readFileSync(tokenFile, 'utf8').trim());
    await button('登录').click();
    await heading('总览').waitFor();
    await nav('代理');
    await shot('proxies');
    await button('收起侧栏').click();
    await page.reload();
    await button('展开侧栏').waitFor();
    await button('展开侧栏').click();
    await nav('代理');
    await button('新建代理').click();
    await page.getByLabel('名称', { exact: true }).fill('我的代理');
    await page.getByLabel('协议', { exact: true }).selectOption('socks');
    assert.equal(await page.getByLabel('用户名').count(), 1);
    await page.getByLabel('协议', { exact: true }).selectOption('vless');
    assert.equal(await page.getByLabel('入口服务器', { exact: true }).count(), 0);
    await page.getByLabel('出网方式').selectOption('chain');
    assert.ok(await page.getByLabel('落地 1').count());
    await shot('proxy-editor');
    await close();
    const first = page.locator('tbody tr').filter({ hasText: '三跳代理' });
    // A single row must not clip its menu inside the table's scroll container.
    await page.getByLabel('搜索代理名称、客户、服务器、地址或端口').fill('三跳代理');
    await first.getByRole('button', { name: '三跳代理 更多操作' }).click();
    const menu = page.getByRole('menu');
    await menu.waitFor();
    assert.equal(await menu.getByRole('menuitem').count(), 10);
    assert.equal(await menu.getByRole('menuitem', {name:'日志与诊断',exact:true}).count(), 1);
    assert.equal(await menu.evaluate(el => el.closest('.overflow-x-auto')), null);
    const remove = menu.getByRole('menuitem', { name: '删除代理', exact: true });
    assert.ok(await remove.evaluate(el => {
      const r = el.getBoundingClientRect();
      return el.contains(document.elementFromPoint(r.x + r.width / 2, r.y + r.height / 2));
    }), 'Last menu item must be visible and unobstructed');
    await page.keyboard.press('Escape');
    await menu.waitFor({ state: 'hidden' });
    assert.equal(await first.getByRole('button', { name: '三跳代理 更多操作' }).evaluate(el => el === document.activeElement), true);
    await page.getByLabel('搜索代理名称、客户、服务器、地址或端口').fill('');
    await first.getByRole('button', { name: '三跳代理 更多操作' }).click();
    await page.getByRole('menuitem', { name: '分享配置', exact: true }).click();
    await page.waitForFunction(() => document.querySelector('textarea[aria-label="Mihomo 节点配置"]')?.value.startsWith('- '));
    const yaml = await page.getByLabel('Mihomo 节点配置').inputValue();
    assert.equal(JSON.parse(yaml.slice(2)).type, 'vless');
    assert.doesNotMatch(yaml, /^(proxies|proxy-groups|rules):/m, 'Share one node, not a full profile');
    const download = page.waitForEvent('download');
    await button('下载').click();
    const file = await download;
    assert.equal(file.suggestedFilename(), 'proxy.yaml');
    const downloaded = path.join(artifacts, 'browser-export.yaml');
    await file.saveAs(downloaded);
    assert.equal(fs.readFileSync(downloaded, 'utf8'), yaml);
    await shot('mihomo');
    await button('链接 / 二维码').click();
    await page.getByAltText('接入二维码').waitFor();
    assert.match(await page.getByLabel('分享链接').inputValue(), /^vless:\/\//);
    await shot('share');
    await close();
    await nav('外部代理');
    await shot('external-proxies');
    assert.equal(await button('添加中转入口').count(), 0);
    assert.equal(await button('添加远程服务器').count(), 0);
    await nav('设置');
    await shot('settings');
    const cdp = await context.newCDPSession(page);
    await cdp.send('WebAuthn.enable');
    const { authenticatorId } = await cdp.send('WebAuthn.addVirtualAuthenticator', { options: {
      protocol: 'ctap2', transport: 'internal', hasResidentKey: true,
      hasUserVerification: true, automaticPresenceSimulation: true, isUserVerified: true,
    } });
    await button('添加 Passkey').click();
    await page.getByLabel('凭据名称').fill('测试安全密钥');
    await page.getByLabel('当前管理员密钥').fill(fs.readFileSync(tokenFile, 'utf8').trim());
    await button('验证并绑定').click();
    await page.getByRole('dialog').waitFor({ state: 'hidden', timeout: 30000 });
    await page.getByText('测试安全密钥', { exact: true }).waitFor();
    await button('退出登录').click();
    await button('使用 Passkey 登录').click();
    await heading('设置').waitFor();
    await button('删除 测试安全密钥').click();
    await page.getByLabel('当前管理员密钥').fill(fs.readFileSync(tokenFile, 'utf8').trim());
    await button('验证并撤销').click();
    await page.getByRole('dialog').waitFor({ state: 'hidden' });
    await cdp.send('WebAuthn.removeVirtualAuthenticator', { authenticatorId });
    await cdp.detach();
    await page.setViewportSize({ width: 390, height: 844 });
    await button('打开导航').click();
    await nav('代理');
    assert.equal(await page.evaluate(() => document.documentElement.scrollWidth <= innerWidth), true, 'mobile overflow');
    await shot('mobile');
    await button('打开导航').click();
    await nav('代理');
    await button('新建代理').click();
    const box = await page.getByRole('dialog').boundingBox();
    assert.ok(box.x >= 0 && box.x + box.width <= 390, 'mobile dialog overflow');
    await shot('mobile-editor');
    await close();
    assert.deepEqual(errors, [], 'Browser errors');
    await context.close();
    console.log('PASS browser save/apply, QR/node YAML, sidebar, external proxy management, WebAuthn registration/login/revocation and mobile layout');
  } finally {
    if (browser) await browser.close();
    await server.close();
    console.log(`CLEANUP browser pid=${record.browserPid}`);
  }
})().catch(error => { console.error(error); process.exitCode = 1; });
