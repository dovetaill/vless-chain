const fs = require('node:fs');
const assert = require('node:assert/strict');
const {chromium} = require(process.env.CHAIN_TEST_BROWSER);
const [base, tokenFile, remote] = process.argv.slice(2);
(async () => {
  const server = await chromium.launchServer({headless:true, executablePath:process.env.CHAIN_TEST_CHROMIUM, args:['--no-sandbox']});
  console.log('BROWSER pid='+server.process().pid);
  let browser;
  try {
    browser = await chromium.connect(server.wsEndpoint());
    const page = await browser.newPage();
    const errors=[];page.on('pageerror', e=>errors.push(e.message));
    const button = name=>page.getByRole('button',{name,exact:true});
    const nav = async name=>{await page.locator('aside nav').getByRole('button',{name:new RegExp('^'+name)}).click();};
    await page.goto(base+'/admin');
    await page.getByLabel('管理员密钥',{exact:true}).fill(fs.readFileSync(tokenFile,'utf8').trim());
    await button('登录').click();
    await page.getByRole('heading',{name:'总览',exact:true}).waitFor();
    await page.goto(base+'/admin?remote='+remote+'#resources');
    await button('新建资源组').click();
    await page.getByLabel('名称',{exact:true}).fill('浏览器资源');
    await page.getByLabel('上下行合计共享上限（Mbps）',{exact:true}).fill('100');
    const zone=page.getByLabel('时区',{exact:true});
    assert.equal(await zone.count(),1);
    await zone.fill('America/New_York');
    await page.getByLabel('每月重置日',{exact:true}).fill('21');
    await button('保存并下发').click();
    await page.getByRole('dialog').waitFor({state:'hidden'});
    await page.getByText('· 上下行合计 100 Mbps',{exact:false}).waitFor();
    await button('设置 / 成员').click();
    assert.equal(await page.getByLabel('时区',{exact:true}).inputValue(),'America/New_York');
    await page.getByRole('dialog').getByRole('button',{name:'关闭',exact:true}).last().click();
    await button('删除空组').click();
    await page.getByText('浏览器资源',{exact:true}).waitFor({state:'hidden'});
    await nav('网站规则');
    await page.getByLabel('筛选网站规则').fill('dアニメ');
    await button('载入内置规则').click();
    await button('应用新版本').click();
    await nav('代理');
    await button('sharing-policy 更多操作').click();
    await page.getByRole('menuitem',{name:'网站 / 端口 / 连接限制',exact:true}).click();
    await page.getByLabel('禁止目标端口（逗号或空格分隔）',{exact:true}).fill('25, 465');
    await page.getByLabel('UDP 策略',{exact:true}).selectOption('ports');
    await page.getByLabel('UDP 允许端口',{exact:true}).fill('53, 443');
    await button('保存并下发').click();
    await page.getByRole('dialog').waitFor({state:'hidden'});
    await button('sharing-policy 更多操作').click();
    await page.getByRole('menuitem',{name:'网站 / 端口 / 连接限制',exact:true}).click();
    assert.equal(await page.getByLabel('UDP 策略',{exact:true}).inputValue(),'ports');
    assert.equal(await page.getByLabel('禁止目标端口（逗号或空格分隔）',{exact:true}).inputValue(),'25, 465');
    assert.deepEqual(errors,[]);
    console.log('PASS real remote UI: resources CRUD, bandwidth wording, timezone label, built-in apply, access policy save/reopen');
  } finally {
    if(browser)await browser.close();
    await server.close();
    assert(server.process().exitCode!==null || server.process().signalCode!==null);
    console.log('CLEANUP browser stopped');
  }
})().catch(e=>{console.error(e);process.exitCode=1;});
